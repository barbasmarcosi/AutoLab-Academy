import{test,expect}from'@playwright/test';
test('RW2/RW3 physics: hypothesis first, independent accounting, portfolio and reload',async({page})=>{
 await page.goto('./');
 await page.locator('nav.nav button[data-id="rotary-thermal"]').click();
 await expect(page.getByRole('heading',{name:'Thermodynamics Research Bench'})).toBeVisible();
 await expect(page.getByText(/Dos modelos independientes/)).toBeVisible();
 await page.locator('#rt-a').selectOption('8');
 await page.locator('#rt-b').selectOption('12');
 await page.locator('#rt-gamma').selectOption('1.4');
 await page.locator('#rt-q').selectOption('200');
 await page.locator('#rt-ideal').selectOption('aumenta');
 await page.locator('#rt-residual').selectOption('resto');
 await page.locator('#rt-real').selectOption('no');
 await page.getByRole('button',{name:'Congelar hipótesis y contrastar'}).click();
 await expect(page.getByText('Ciclo ideal Otto de aire estándar, no simulación de Wankel real')).toBeVisible();
 await expect(page.getByText('RW3 — Balance ficticio de potencia y conservación')).toBeVisible();
 await page.locator('#rt-reason').fill('El ciclo ideal usa gamma fija y una compresión mayor, por lo que crece la eficiencia aritmética. El balance inventado es independiente; debo medir consumo y potencia real bajo condiciones comparables.');
 await page.locator('#rt-limits').fill('No se simulan combustión, puertos, sellos, pérdidas ni la presión real del motor; las hipótesis requieren evidencia y pruebas físicas independientes.');
 await page.getByRole('button',{name:'Evaluar informe RW2/RW3'}).click();
 await expect(page.getByText(/Resultado: 100\/100/)).toBeVisible();
 await page.getByRole('button',{name:'Guardar expediente RW2/RW3'}).click();
 await expect(page.getByRole('button',{name:'Evidencia registrada'})).toBeDisabled();
 await page.locator('nav.nav button[data-id="portfolio"]').click();
 await expect(page.getByText('RW2/RW3 — Termodinámica y balance energético')).toBeVisible();
 await page.reload();await page.locator('nav.nav button[data-id="portfolio"]').click();
 await expect(page.getByText('RW2/RW3 — Termodinámica y balance energético')).toBeVisible();
});
