import{test,expect}from'@playwright/test';
const visit=async(page,title)=>{
 await page.goto('./');await page.locator('nav.nav button[data-id="learn"]').click();
 const card=page.locator('article.lesson-card').filter({hasText:title});
 await card.getByRole('button',{name:'Estudiar'}).click();
 return card;
};
test('MC06 learns theory, predicts virtual measurements and stores approved practice independently of reading',async({page})=>{
 await visit(page,'MC06+ — Deslizamiento, sensor');
 await expect(page.locator('#lesson-practice-host [data-pt="new"]')).toBeVisible();
 await expect(page.locator('#lesson-practice-status')).toContainText('no registrada');
 await page.evaluate(()=>{Math.random=()=>1.5/2147483647;});
 await page.getByRole('button',{name:'Crear investigación MC06'}).click();
 await page.locator('#pt-initial').selectOption('slip');
 await page.getByRole('button',{name:'Congelar hipótesis'}).click();
 await page.locator('#pt-independent').selectOption('normal');
 await page.getByRole('button',{name:/Congelar y revelar Tacómetro independiente/}).click();
 await page.locator('#pt-reference').selectOption('large');
 await page.getByRole('button',{name:/Congelar y revelar Chequeo independiente/}).click();
 await page.locator('#pt-final').selectOption('sensor');
 await page.locator('#pt-reason').fill('La entrada reduce RPM bajo un factor tres, pero la lectura inicial por sí sola no demuestra deslizamiento. La referencia del canal y el tacómetro independiente explican el sesgo y rechazan el defecto mecánico programado.');
 await page.locator('#pt-limits').fill('Este modelo es ficticio y no puede validar una caja real. Faltan condiciones de carga, tolerancias de sensor, referencia OEM e instrumentación metrológica independiente.');
 await page.getByRole('button',{name:'Evaluar investigación'}).click();
 await expect(page.getByText(/Resultado: 100\/100/)).toBeVisible();
 await page.getByRole('button',{name:'Guardar investigación MC06'}).click();
 await expect(page.locator('#lesson-practice-status')).toContainText('Práctica aprobada');
 await expect(page.locator('#lesson-theory-practice-status')).toContainText('Práctica aprobada');
 await expect(page.getByText(/Teoría: lectura pendiente/)).toBeVisible();
 await page.getByRole('button',{name:'Registrar lectura y volver'}).click();
 const card=page.locator('article.lesson-card').filter({hasText:'MC06+ — Deslizamiento, sensor'});
 await expect(card).toContainText('Lectura registrada');
 await expect(card).toContainText('Práctica aprobada');
 await page.reload();await page.locator('nav.nav button[data-id="learn"]').click();
 await expect(page.locator('article.lesson-card').filter({hasText:'MC06+ — Deslizamiento, sensor'})).toContainText('Práctica aprobada');
});
