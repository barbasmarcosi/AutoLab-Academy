import{test,expect}from'@playwright/test';
import{readFile}from'node:fs/promises';
test('lesson 2: before reading DTC misconception baseline is ungraded and gives individual explanations',async({page})=>{
 await page.goto('./');
 await page.getByRole('button',{name:'Academia',exact:true}).click();
 await page.locator('.lesson-card').filter({hasText:'DTC y parámetros: síntomas, no sentencias'}).getByRole('button',{name:'Estudiar'}).click();
 const baseline=page.locator('#dtc-baseline-host');
 await expect(baseline.getByText('Antes de leer: ¿qué creés que informa un DTC?')).toBeVisible();
 await baseline.locator('#dtc-baseline-check').click();
 await expect(baseline.locator('#dtc-baseline-result')).toContainText('Respondé las tres preguntas');
 await baseline.locator('input[name="dtc-baseline-code"][value="0"]').check();
 await baseline.locator('input[name="dtc-baseline-trim"][value="0"]').check();
 await baseline.locator('input[name="dtc-baseline-contrast"][value="2"]').check();
 await baseline.locator('#dtc-baseline-check').click();
 await expect(baseline.locator('#dtc-baseline-result')).toContainText('Revisá esta idea');
 await expect(baseline.locator('#dtc-baseline-result')).toContainText('El resultado no se guarda');
});
test('lesson 2: independent DTC holdout freezes prior forecast, rejects shortcuts and stores a full trace',async({page})=>{
 await page.goto('./');
 await page.getByRole('button',{name:'Academia',exact:true}).click();
 await page.locator('.lesson-card').filter({hasText:'DTC y parámetros: síntomas, no sentencias'}).getByRole('button',{name:'Estudiar'}).click();
 const h=page.locator('#dtc-holdout-host');
 await expect(h.getByText('Caso reservado: diagnóstico sin solución a la vista')).toBeVisible();
 await expect(h).toContainText('Banco R01');
 await h.locator('[data-dtc-h="freeze"]').click();
 await expect(h.locator('#dtc-h-status')).toContainText('Congelá hipótesis');
 await h.locator('#dtc-h-prior').selectOption('fuel');
 await h.locator('#dtc-h-first').selectOption('pressure');
 await h.locator('#dtc-h-predict').selectOption('normal');
 await h.locator('[data-dtc-h="freeze"]').click();
 await expect(h.locator('#dtc-h-frozen')).toContainText('Suministro insuficiente');
 await h.locator('#dtc-h-probe').selectOption('trims');
 await h.locator('[data-dtc-h="measure"]').click();
 await expect(h.locator('#dtc-h-status')).toContainText('primera medición');
 await expect(h.locator('#dtc-h-observed')).toContainText('0/4');
 for(const [i,k] of ['pressure','trims','leak','sensor'].entries()){
  await h.locator('#dtc-h-probe').selectOption(k);
  await h.locator('[data-dtc-h="measure"]').click();
  await expect(h.locator('#dtc-h-observed')).toContainText((i+1)+'/4');
 }
 await expect(h.locator('#dtc-h-observed')).toContainText('3,4 bar');
 await expect(h.locator('#dtc-h-observed')).toContainText('aire no medido');
 await expect(h.locator('[data-dtc-h="measure"]')).toBeDisabled();
 await h.locator('#dtc-h-diagnosis').selectOption('air');
 await h.locator('#dtc-h-decisive').selectOption('leak');
 await h.locator('input[name="dtc-h-falsifier"][value="0"]').check();
 await h.locator('[data-dtc-h="grade"]').click();
 await expect(h.locator('#dtc-h-status')).toContainText('Registrá razonamiento y alternativa');
 await h.locator('#dtc-h-why').fill('La presión es compatible con la referencia interna y hay un indicio de entrada de aire no medida.');
 await h.locator('#dtc-h-alternative').fill('Consideré falta de suministro, pero la presión normal la debilita.');
 await h.locator('[data-dtc-h="grade"]').click();
 await expect(h.locator('#dtc-h-result')).toContainText('100/100');
 await expect(h.locator('#dtc-h-result')).toContainText('pendiente de revisión humana');
 await expect(h.locator('#dtc-h-result')).toContainText('revisada: sí');
 await expect(page.locator('#lesson-theory-practice-status')).toContainText('caso independiente completados');
 await page.locator('nav.nav button[data-id="data"]').click();
 const download=page.waitForEvent('download');
 await page.locator('[data-action="export"]').click();
 const file=JSON.parse(await readFile(await(await download).path(),'utf8'));
 const saved=file.payload.cases.findLast(x=>x.id==='lab-dtc-holdout-v1');
 expect(saved).toMatchObject({score:100,passed:true});
 const report=JSON.parse(saved.report);
 expect(report).toMatchObject({caseId:'R01',rubric:'lab-dtc-holdout-v1',qualitativeReview:'pending',final:{diagnosis:'air',decisiveTest:'leak',falsifier:0}});
 expect(report.prior).toMatchObject({hypothesis:'fuel',firstTest:'pressure',expectedObservation:'normal'});
 expect(report.measurementsInOrder).toEqual(['pressure','trims','leak','sensor']);
 expect(report.observations).toHaveLength(4);
});
test('lesson 2: offline learner transfer goes to next reserved scenario after previous submission',async({page})=>{
 await page.goto('./');
 await page.getByRole('button',{name:'Academia',exact:true}).click();
 await page.locator('.lesson-card').filter({hasText:'DTC y parámetros: síntomas, no sentencias'}).getByRole('button',{name:'Estudiar'}).click();
 const h=page.locator('#dtc-holdout-host');
 await h.locator('#dtc-h-prior').selectOption('undetermined');
 await h.locator('#dtc-h-first').selectOption('trims');
 await h.locator('#dtc-h-predict').selectOption('uncertain');
 await h.locator('[data-dtc-h="freeze"]').click();
 for(const k of ['trims','leak','pressure','sensor']){
  await h.locator('#dtc-h-probe').selectOption(k);
  await h.locator('[data-dtc-h="measure"]').click();
 }
 await h.locator('#dtc-h-diagnosis').selectOption('air');
 await h.locator('#dtc-h-decisive').selectOption('leak');
 await h.locator('input[name="dtc-h-falsifier"][value="0"]').check();
 await h.locator('#dtc-h-why').fill('Pruebas independientes apoyan entrada de aire.');
 await h.locator('#dtc-h-alternative').fill('Presión y sensor plausibles.');
 await h.locator('[data-dtc-h="grade"]').click();
 await expect(h.locator('#dtc-h-result')).toContainText('100/100');
 await h.locator('[data-dtc-h="again"]').click();
 await expect(h).toContainText('Banco R02');
 await page.reload();
 await page.getByRole('button',{name:'Academia',exact:true}).click();
 await page.locator('.lesson-card').filter({hasText:'DTC y parámetros: síntomas, no sentencias'}).getByRole('button',{name:'Estudiar'}).click();
 await expect(page.locator('#dtc-holdout-host')).toContainText('Banco R02');
});
